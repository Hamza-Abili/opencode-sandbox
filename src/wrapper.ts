/**
 * opencode-sandbox — runtime files.
 *
 * A small generated wrapper is handed to OpenCode as the shell executable.
 * OpenCode invokes it as `wrapper -c '<original command>'` with the requested
 * cwd; the wrapper validates that cwd and execs bwrap/sandbox-exec. The
 * original command is never rewritten, so permissions and history see it.
 *
 * The wrapper lives in a 0700 directory outside the writable sandbox trees.
 * It is generated once per plugin instance and removed on dispose.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { type Resolved, resolveSandboxBinary } from "./binary.ts";
import { buildDarwinProfile, darwinEnvironment } from "./darwin.ts";
import { contains } from "./paths.ts";
import { probe } from "./probe.ts";
import { buildLinuxProfile } from "./profile.ts";
import { shellJoin } from "./quote.ts";
import type { Platform, SandboxLayout, SandboxOptions } from "./types.ts";

export interface SandboxRuntime {
  platform: Platform;
  binary: string;
  shell: string;
  layout: SandboxLayout;
  options: SandboxOptions;
  dir: string;
  wrapper: string;
  dispose(): void;
}

export type RuntimeResult = { ok: true; runtime: SandboxRuntime } | { ok: false; reason: string };

function isSafeBase(base: string, layout: SandboxLayout, platform: Platform): boolean {
  let resolved: string;
  try {
    resolved = fs.realpathSync.native(base);
  } catch {
    return false;
  }
  const writable = [layout.workspace, ...layout.writablePaths];
  if (writable.some((root) => contains(root, resolved))) return false;
  if (platform === "darwin") {
    // The macOS profile allows writes under the OS temp dirs. A wrapper or
    // profile placed there would be modifiable by the sandboxed command.
    const unsafe = ["/private/tmp", "/tmp", "/private/var/folders", "/var/folders"];
    if (unsafe.some((root) => contains(root, resolved))) return false;
  }
  return true;
}

function createRuntimeDir(layout: SandboxLayout, platform: Platform): string {
  const homeCache = path.join(os.homedir(), ".cache");
  const homeLibraryCache = path.join(os.homedir(), "Library", "Caches");
  const bases = [
    process.env.XDG_RUNTIME_DIR,
    homeCache,
    ...(platform === "darwin" ? [homeLibraryCache] : [os.tmpdir(), "/tmp"]),
  ].filter((value): value is string => typeof value === "string" && path.isAbsolute(value));

  const tried: string[] = [];
  for (const base of bases) {
    try {
      if (!fs.existsSync(base)) {
        // Only per-user cache dirs are created here; system temp dirs exist.
        if (base !== homeCache && base !== homeLibraryCache) continue;
        fs.mkdirSync(base, { recursive: true, mode: 0o700 });
      }
      if (!isSafeBase(base, layout, platform)) {
        tried.push(`${base} (inside a writable mount)`);
        continue;
      }
      const dir = fs.mkdtempSync(path.join(base, "opencode-sandbox-"));
      fs.chmodSync(dir, 0o700);
      const resolved = fs.realpathSync.native(dir);
      if (!isSafeBase(resolved, layout, platform)) {
        fs.rmSync(dir, { recursive: true, force: true });
        tried.push(`${base} (resolves inside a writable mount)`);
        continue;
      }
      return resolved;
    } catch (error) {
      tried.push(`${base} (${error instanceof Error ? error.message : String(error)})`);
    }
  }
  throw new Error(`no safe runtime directory: ${tried.join("; ")}`);
}

function cwdGuard(layout: SandboxLayout): string {
  const patterns = [layout.workspace, ...layout.writablePaths, ...layout.readablePaths]
    .map((root) => `${shellQuotePattern(root)}|${shellQuotePattern(root)}/*`)
    .join("|");
  return [
    'cwd=$(pwd -P) || { echo "opencode-sandbox: cannot determine the working directory" >&2; exit 126; }',
    `case "$cwd" in`,
    `  ${patterns}) ;;`,
    `  *) echo "opencode-sandbox: working directory outside the sandbox: $cwd" >&2; exit 126 ;;`,
    "esac",
  ].join("\n");
}

export function shellQuotePattern(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

const HEADER = [
  "#!/bin/sh",
  "# Generated by @hamzaabili/opencode-sandbox. Do not edit.",
  "set -eu",
  // biome-ignore lint/suspicious/noTemplateCurlyInString: shell parameter expansion
  'if [ "${1:-}" != "-c" ] || [ "$#" -lt 2 ]; then',
  '  echo "opencode-sandbox: unsupported shell invocation" >&2',
  "  exit 126",
  "fi",
].join("\n");

function linuxScript(runtime: Omit<SandboxRuntime, "dispose">, args: string[]): string {
  const { binary, shell } = runtime;
  const invocation = [
    shellJoin([binary, ...args]),
    "--chdir",
    '"$cwd"',
    "--",
    shellQuotePattern(shell),
    "-c",
    '"$2"',
  ].join(" ");
  return `${HEADER}\n${cwdGuard(runtime.layout)}\nexec ${invocation}\n`;
}

function darwinScript(
  runtime: Omit<SandboxRuntime, "dispose">,
  profilePath: string,
  env: Record<string, string>
): string {
  const envTokens = Object.entries(env).map(([key, value]) => `${key}=${value}`);
  const invocation = [
    shellJoin([
      "/usr/bin/env",
      "-i",
      ...envTokens,
      runtime.binary,
      "-f",
      profilePath,
      runtime.shell,
      "-c",
    ]),
    '"$2"',
  ].join(" ");
  return `${HEADER}\n${cwdGuard(runtime.layout)}\nexec ${invocation}\n`;
}

export async function prepareRuntime(
  platform: Platform,
  layout: SandboxLayout,
  options: SandboxOptions
): Promise<RuntimeResult> {
  const binary: Resolved = resolveSandboxBinary(platform);
  if (!binary.ok) return { ok: false, reason: binary.reason };

  const result = await probe(platform, binary.path);
  if (!result.available) {
    return { ok: false, reason: result.reason ?? `${binary.path} cannot create a sandbox` };
  }

  let dir: string;
  try {
    dir = createRuntimeDir(layout, platform);
  } catch (error) {
    return { ok: false, reason: error instanceof Error ? error.message : String(error) };
  }

  const cleanup = () => {
    try {
      fs.rmSync(dir, { recursive: true, force: true });
    } catch {
      // best effort
    }
  };

  try {
    const base: Omit<SandboxRuntime, "dispose"> = {
      platform,
      binary: binary.path,
      shell: options.shell,
      layout,
      options,
      dir,
      wrapper: path.join(dir, "shell"),
    };

    let script: string;
    if (platform === "linux") {
      script = linuxScript(
        base,
        buildLinuxProfile({
          layout,
          network: options.network,
          passEnv: options.passEnv,
          shell: options.shell,
          env: process.env,
        })
      );
    } else {
      const home = path.join(dir, "home");
      for (const sub of ["", "tmp", ".cache", ".config", ".local", ".local/share"]) {
        fs.mkdirSync(path.join(home, sub), { recursive: true, mode: 0o700 });
      }
      const profilePath = path.join(dir, "profile.sb");
      const profile = buildDarwinProfile({
        layout,
        home,
        network: options.network,
        passEnv: options.passEnv,
        shell: options.shell,
        env: process.env,
      });
      fs.writeFileSync(profilePath, profile, { mode: 0o600, flag: "wx" });
      script = darwinScript(
        base,
        profilePath,
        darwinEnvironment({
          layout,
          home,
          network: options.network,
          passEnv: options.passEnv,
          shell: options.shell,
          env: process.env,
        })
      );
    }

    fs.writeFileSync(base.wrapper, script, { mode: 0o700, flag: "wx" });
    fs.chmodSync(base.wrapper, 0o700);
    return {
      ok: true,
      runtime: {
        ...base,
        dispose: cleanup,
      },
    };
  } catch (error) {
    cleanup();
    return { ok: false, reason: error instanceof Error ? error.message : String(error) };
  }
}
